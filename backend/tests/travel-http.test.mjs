import {test} from 'node:test';
import assert from 'node:assert/strict';
import http from 'node:http';
import {readFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
import {createPresetService} from '../src/presets.mjs';
import {TravelStore} from '../src/travel/store.mjs';
import {createTravelApi} from '../src/travel/api.mjs';
test('HTTP session → recommendation → save → start, with ownership protection',async t=>{
 const root=fileURLToPath(new URL('../..',import.meta.url));
 const catalog=['places','facilities'].flatMap(f=>JSON.parse(readFileSync(new URL(`../../frontend/src/content/${f}.json`,import.meta.url),'utf8')));
 const store=new TravelStore(':memory:'),api=createTravelApi({root,store,presets:createPresetService(root,catalog)});
 const server=http.createServer((req,res)=>api.handle(req,res,new URL(req.url,'http://localhost')));
 await new Promise(resolve=>server.listen(0,'127.0.0.1',resolve));
 t.after(async()=>{await new Promise(resolve=>server.close(resolve));await api.close();});
 const base=`http://127.0.0.1:${server.address().port}/api/v1`;
 const req=async(path,method='GET',body,token)=>{const r=await fetch(base+path,{method,headers:{'Content-Type':'application/json',...(token?{Authorization:'Bearer '+token}:{})},body:body?JSON.stringify(body):undefined});return {status:r.status,data:await r.json()};};
 assert.equal((await req('/trips')).status,401);
 const token=(await req('/sessions','POST')).data.token;
 const preferences={entrance_id:'west',exit_id:'west',duration:'half_day',intensity:'easy',has_elderly:true,has_children:true};
 const result=await req('/planner/recommend','POST',preferences,token);assert.equal(result.data.count,2);
 const trip=(await req('/trips','POST',{client_event_id:'create',preferences,route_id:'R02',revision:1},token)).data;
 assert.equal((await req(`/trips/${trip.id}/commands`,'POST',{client_event_id:'start',expected_version:1,action:'start'},token)).data.status,'active');
 const foreign=(await req('/sessions','POST')).data.token;
 assert.equal((await req(`/trips/${trip.id}`,'GET',undefined,foreign)).status,404);
 assert.equal((await req(`/trips/${trip.id}/events`,'GET',undefined,token)).data.events.length,2);
 assert.equal((await req(`/trips/${trip.id}`,'DELETE',{expected_version:2},foreign)).status,404);
 const ended=(await req(`/trips/${trip.id}/commands`,'POST',{client_event_id:'end',expected_version:2,action:'complete'},token)).data;
 assert.equal((await req(`/trips/${trip.id}`,'DELETE',{expected_version:ended.version},token)).data.deleted,true);
 assert.equal((await req(`/trips/${trip.id}`,'GET',undefined,token)).status,404);
 assert.equal((await req('/trips','GET',undefined,token)).data.trips.length,0);
});
