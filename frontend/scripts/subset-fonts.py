"""Generate variable first-screen subsets; retain complete Fontsource glyph fallback.
Install fonttools[woff]==4.68.0. Run from any directory after npm ci.
Generated WOFF2/CSS are checked in; normal builds do not require Python.
"""
from pathlib import Path
import hashlib
import re
from fontTools import subset
from fontTools.ttLib import TTFont

root = Path(__file__).resolve().parents[1]
text = (root / 'src/content/font-core.txt').read_text(encoding='utf-8')
core = set(map(ord, text)) | set(range(32, 127))
dest = root / 'src/content/fonts'
dest.mkdir(parents=True, exist_ok=True)

def ranges(codes):
    groups = []
    for n in sorted(codes):
        if groups and groups[-1][1] + 1 == n:
            groups[-1][1] = n
        else:
            groups.append([n, n])
    return ','.join('U+%X' % a + ('-%X' % b if a != b else '') for a, b in groups)

css = ['/* Generated by scripts/subset-fonts.py. Full fallback preserves arbitrary chat text. */']
total = 0
for family in ['noto-sans-sc', 'noto-serif-sc']:
    package = root / 'node_modules/@fontsource-variable' / family
    source = (package / 'index.css').read_text(encoding='utf-8')
    for block in re.findall(r'@font-face\s*\{[^}]+\}', source):
        rel = re.search(r'url\(([^)]+)\)', block).group(1)
        raw_range = re.search(r'unicode-range:\s*([^;]+)', block).group(1)
        codes = set()
        for entry in raw_range.split(','):
            parts = entry.strip()[2:].split('-')
            codes.update(range(int(parts[0],16),int(parts[-1],16)+1))
        covered = codes & core
        fallback = block.replace(rel, '../../node_modules/@fontsource-variable/' + family + '/' + rel.removeprefix('./'))
        if covered:
            font = TTFont(package / rel, recalcTimestamp=False)
            opts = subset.Options(); opts.flavor = 'woff2'
            job = subset.Subsetter(options=opts); job.populate(unicodes=covered); job.subset(font)
            # Hash source and subset inputs, not timestamps, for stable asset names.
            digest = hashlib.sha256((package / rel).read_bytes() + ranges(covered).encode() + b'v1').hexdigest()[:12]
            name = family + '-core-' + digest + '.woff2'
            font.save(dest / name); font.close()
            total += (dest / name).stat().st_size
            css.append(block.replace(rel, './fonts/' + name).replace(raw_range, ranges(covered)))
            if codes-core:
                css.append(fallback.replace(raw_range, ranges(codes-core)))
        else:
            css.append(fallback)
(root / 'src/content/fonts.css').write_text('\n'.join(css)+'\n', encoding='utf-8')
print('First-screen variable subsets: %d bytes. Complete fonts remain on-demand fallbacks.' % total)
